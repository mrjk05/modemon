// Inputs

export type ToolRequest =
  | {
      action: 'record'
      title: string
      context: string
      decision: string
      alternatives: string[]
      consequences: string
      tags: string[]
      files: string[]
      deciders: string[]
      status: DecisionStatus
      supersedes: number[]
    }
  | { action: 'list'; status?: string; tag?: string }
  | { action: 'search'; query: string }
  | { action: 'get'; id: number }
  | { action: 'supersede'; id: number; by: number }
  | { action: 'set-status'; id: number; status: DecisionStatus }
  | { action: 'error'; message: string }

function str(v: unknown): string {
  return typeof v === 'string' ? v : typeof v === 'number' ? String(v) : ''
}

function strList(v: unknown): string[] {
  if (typeof v === 'string') return v.split(',').map(s => oneLine(s)).filter(s => s !== '')
  if (!Array.isArray(v)) return []
  return v.map(x => oneLine(str(x))).filter(s => s !== '')
}

function idOf(v: unknown): number | undefined {
  const n = typeof v === 'number' ? v : Number(/\d+/.exec(str(v))?.[0])
  return Number.isSafeInteger(n) && n > 0 ? n : undefined
}

export function parseToolInput(input: Record<string, unknown>): ToolRequest {
  const action = str(input.action)
  switch (action) {
    case 'record': {
      const title = oneLine(str(input.title))
      if (title === '') return { action: 'error', message: 'record needs a "title".' }
      const decision = str(input.decision).trim()
      if (decision === '') return { action: 'error', message: 'record needs "decision": what was decided.' }
      const statusRaw = input.status === undefined ? 'accepted' : str(input.status)
      const status = normStatus(statusRaw)
      if (status === undefined || status === 'superseded') {
        return { action: 'error', message: `record "status" must be proposed, accepted or rejected, not "${statusRaw}".` }
      }
      const supersedes = (Array.isArray(input.supersedes) ? input.supersedes : input.supersedes === undefined ? [] : [input.supersedes])
        .map(idOf)
        .filter((n): n is number => n !== undefined)
      const deciders = strList(input.deciders)
      return {
        action,
        title,
        context: str(input.context).trim(),
        decision,
        alternatives: Array.isArray(input.alternatives) ? input.alternatives.map(a => str(a).trim()).filter(a => a !== '') : strList(input.alternatives),
        consequences: str(input.consequences).trim(),
        tags: strList(input.tags).map(t => t.toLowerCase()),
        files: strList(input.files),
        deciders: deciders.length > 0 ? deciders : ['user', 'claude'],
        status,
        supersedes,
      }
    }
    case 'list': {
      const status = input.status === undefined ? undefined : str(input.status)
      if (status !== undefined && normStatus(status) === undefined) return { action: 'error', message: `Unknown status "${status}".` }
      return { action, status, tag: input.tag === undefined ? undefined : str(input.tag) }
    }
    case 'search': {
      const query = str(input.query).trim()
      return query === '' ? { action: 'error', message: 'search needs a "query".' } : { action, query }
    }
    case 'get': {
      const id = idOf(input.id)
      return id === undefined ? { action: 'error', message: 'get needs an "id" (the record number).' } : { action, id }
    }
    case 'supersede': {
      const id = idOf(input.id)
      const by = idOf(input.by)
      if (id === undefined || by === undefined) return { action: 'error', message: 'supersede needs "id" (the old record) and "by" (the new one).' }
      if (id === by) return { action: 'error', message: 'A record cannot supersede itself.' }
      return { action, id, by }
    }
    case 'set-status': {
      const id = idOf(input.id)
      const status = normStatus(str(input.status))
      if (id === undefined || status === undefined) {
        return { action: 'error', message: 'set-status needs "id" and "status" (proposed, accepted, superseded or rejected).' }
      }
      return { action, id, status }
    }
    default:
      return { action: 'error', message: `Unknown action "${action}". Use record, list, search, get, supersede or set-status.` }
  }
}

/** `/decide <title> — <why>`: the separators, in order of preference, are an em or en dash, `--`, then `:`. */
export function parseDecide(args: string): { title: string; why: string } | { error: string } {
  const text = args.trim()
  const usage = 'Usage: /decide <title> — <why>   (also `--` or `:` between them)'
  if (text === '') return { error: usage }
  for (const sep of [/\s*[—–]\s*/, /\s+--\s+|\s*--\s*/, /\s*:\s+|:\s*/]) {
    const match = sep.exec(text)
    if (match !== null && match.index > 0) {
      const title = oneLine(text.slice(0, match.index).replace(/^["']|["']$/g, ''))
      const why = text.slice(match.index + match[0].length).trim()
      if (title !== '') return { title, why }
    }
  }
  return { title: oneLine(text.replace(/^["']|["']$/g, '')), why: '' }
}

export type DecisionsCommand = { kind: 'list' } | { kind: 'show'; id: number } | { kind: 'search'; query: string } | { kind: 'error'; message: string }

export function parseDecisionsArgs(args: string): DecisionsCommand {
  const text = args.trim()
  if (text === '' || /^(list|ls|all)$/i.test(text)) return { kind: 'list' }
  const show = /^(?:show\s+|get\s+)?#?(\d+)$/i.exec(text)
  if (show !== null) return { kind: 'show', id: Number(show[1]) }
  const found = /^(?:search|find|grep)\s+(.+)$/i.exec(text)
  if (found !== null) return { kind: 'search', query: (found[1] as string).trim() }
  return { kind: 'error', message: 'Usage: /decisions | /decisions <n> | /decisions search <query>' }
}

