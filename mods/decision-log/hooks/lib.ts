// Front matter (a tolerant subset of YAML: scalars, flow lists, block lists)

function unquote(raw: string): string {
  const value = raw.trim()
  if (value.length >= 2 && value.startsWith('"') && value.endsWith('"')) {
    return value.slice(1, -1).replace(/\\(["\\nt])/g, (_m, c: string) => (c === 'n' ? '\n' : c === 't' ? '\t' : c))
  }
  if (value.length >= 2 && value.startsWith("'") && value.endsWith("'")) return value.slice(1, -1).replace(/''/g, "'")
  // A trailing comment on a plain scalar.
  return value.replace(/\s+#.*$/, '')
}

/** Splits `[a, "b, c", d]` (brackets included or not) on commas outside quotes. */
function splitFlow(raw: string): string[] {
  let inner = raw.trim()
  if (inner.startsWith('[')) inner = inner.slice(1)
  if (inner.endsWith(']')) inner = inner.slice(0, -1)
  const parts: string[] = []
  let current = ''
  let quote: string | undefined
  for (let i = 0; i < inner.length; i++) {
    const ch = inner[i] as string
    if (quote !== undefined) {
      current += ch
      if (ch === '\\' && quote === '"' && i + 1 < inner.length) {
        current += inner[++i] as string
      } else if (ch === quote) quote = undefined
    } else if (ch === '"' || ch === "'") {
      quote = ch
      current += ch
    } else if (ch === ',') {
      parts.push(current)
      current = ''
    } else current += ch
  }
  parts.push(current)
  return parts.map(unquote).filter(p => p !== '')
}

type RawMeta = { key: string; scalar?: string; list?: string[]; raw: string }

function parseFrontMatter(lines: string[]): RawMeta[] {
  const out: RawMeta[] = []
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] as string
    if (line.trim() === '' || line.trimStart().startsWith('#')) continue
    const match = /^([A-Za-z_][\w -]*?)\s*:(.*)$/.exec(line)
    if (match === null) continue
    const key = (match[1] as string).trim()
    const rest = (match[2] as string).trim()
    if (rest === '' || rest === '|' || rest === '>') {
      // A block list (`- a`) or a block scalar on the indented lines below.
      const block: string[] = []
      while (i + 1 < lines.length && /^(\s+|-\s)/.test(lines[i + 1] as string) && !/^[A-Za-z_][\w -]*:/.test(lines[i + 1] as string)) {
        block.push(lines[++i] as string)
      }
      const items = block.filter(l => l.trim() !== '')
      if (items.length > 0 && items.every(l => /^\s*-\s/.test(l) || /^\s*-$/.test(l))) {
        out.push({ key, list: items.map(l => unquote(l.replace(/^\s*-\s?/, ''))).filter(v => v !== ''), raw: [rest, ...block].join('\n') })
      } else {
        out.push({ key, scalar: items.map(l => l.trim()).join(rest === '|' ? '\n' : ' '), raw: [rest, ...block].join('\n') })
      }
    } else if (rest.startsWith('[')) {
      out.push({ key, list: splitFlow(rest), raw: rest })
    } else {
      out.push({ key, scalar: unquote(rest), raw: rest })
    }
  }
  return out
}

function normKey(key: string): string {
  const k = key.trim().toLowerCase().replace(/[_ ]+/g, '-')
  if (k === 'supersededby' || k === 'superseded') return 'superseded-by'
  if (k === 'decider' || k === 'deciders') return 'deciders'
  if (k === 'tag' || k === 'tags') return 'tags'
  if (k === 'file' || k === 'files') return 'files'
  return k
}

function listOf(meta: RawMeta): string[] {
  if (meta.list !== undefined) return meta.list
  const scalar = meta.scalar ?? ''
  if (scalar === '' || scalar === '~' || scalar.toLowerCase() === 'null') return []
  return scalar.split(',').map(s => unquote(s)).filter(s => s !== '')
}

function idsOf(meta: RawMeta): number[] {
  const ids: number[] = []
  for (const item of listOf(meta)) {
    for (const match of item.matchAll(/\d+/g)) {
      const n = Number(match[0])
      if (Number.isSafeInteger(n) && n > 0 && !ids.includes(n)) ids.push(n)
    }
  }
  return ids
}

export function normStatus(raw: string | undefined): DecisionStatus | undefined {
  const s = (raw ?? '').trim().toLowerCase()
  if ((STATUSES as readonly string[]).includes(s)) return s as DecisionStatus
  if (s === 'deprecated' || s.startsWith('superseded')) return 'superseded'
  if (s === 'approved' || s === 'done' || s === 'adopted') return 'accepted'
  if (s === 'draft' || s === 'open' || s === 'pending') return 'proposed'
  if (s === 'declined' || s === 'abandoned') return 'rejected'
  return undefined
}

