export function nextId(entries: readonly { id: number; file?: string }[], fileNames: readonly string[] = []): number {
  let max = 0
  for (const e of entries) max = Math.max(max, e.id)
  for (const name of fileNames) max = Math.max(max, idFromFileName(name) ?? 0)
  return max + 1
}

function cell(text: string): string {
  return oneLine(text, 120).replace(/\|/g, '\\|')
}

/** `<dir>/README.md`: a table of every record, oldest first. */
export function renderIndex(entries: readonly DecisionEntry[]): string {
  const rows = [...entries].sort((a, b) => a.id - b.id)
  const lines = [
    '# Decision log',
    '',
    INDEX_MARKER,
    '',
    'Architecture decision records for this repository. Record one with `/decide <title> — <why>` or ask Claude; browse with `/decisions`.',
    '',
    '| # | Title | Status | Date |',
    '| --- | --- | --- | --- |',
    ...rows.map(e => {
      const by = e.status === 'superseded' && e.supersededBy.length > 0 ? ` (by ${e.supersededBy.map(n => `#${n}`).join(', ')})` : ''
      return `| ${pad4(e.id)} | [${cell(e.title)}](${encodeURI(e.file)}) | ${e.status}${by} | ${cell(e.date)} |`
    }),
  ]
  if (rows.length === 0) lines.push('', '_No decisions recorded yet._')
  return `${lines.join('\n')}\n`
}

export function newestFirst<T extends { id: number }>(entries: readonly T[]): T[] {
  return [...entries].sort((a, b) => b.id - a.id)
}

export function supersededNote(d: Pick<Decision, 'supersededBy'>): string {
  return d.supersededBy.length === 0 ? '' : ` → ${d.supersededBy.map(n => `#${n}`).join(', ')}`
}

/** `#7 accepted 2026-10-06 Use SQLite [storage] → #9 (docs/decisions/0007-use-sqlite.md)` */
export function formatLine(e: DecisionEntry): string {
  const tags = e.tags.length > 0 ? ` [${e.tags.join(', ')}]` : ''
  return `#${e.id} ${e.status} ${e.date || '----------'} ${oneLine(e.title, 120)}${tags}${supersededNote(e)} (${e.path})`
}

export function filterEntries(entries: readonly DecisionEntry[], filter: { status?: string; tag?: string }): DecisionEntry[] {
  const status = filter.status === undefined ? undefined : normStatus(filter.status)
  const tag = filter.tag?.trim().toLowerCase()
  return newestFirst(entries).filter(
    e => (status === undefined || e.status === status) && (tag === undefined || tag === '' || e.tags.some(t => t.toLowerCase() === tag)),
  )
}

export function formatList(entries: readonly DecisionEntry[], dirPath: string, filter: { status?: string; tag?: string } = {}): string {
  const shown = filterEntries(entries, filter)
  const what = [filter.status, filter.tag === undefined ? undefined : `tag ${filter.tag}`].filter(Boolean).join(', ')
  if (shown.length === 0) {
    return entries.length === 0 ? `No decisions recorded yet in ${dirPath}/.` : `No decisions match (${what}). ${entries.length} in ${dirPath}/.`
  }
  const head = `${shown.length} decision${shown.length === 1 ? '' : 's'}${what === '' ? '' : ` (${what})`} in ${dirPath}/, newest first:`
  return [head, ...shown.map(formatLine)].join('\n')
}

export function plainBody(d: Decision): string {
  return [d.context, d.decision, ...d.alternatives, d.consequences, ...d.extraSections.map(s => s.body), d.preamble].join('\n')
}

export type SearchHit = { entry: DecisionEntry; score: number; snippet: string }

function snippetAround(text: string, terms: readonly string[], width = 140): string {
  const flat = text.replace(/\s+/g, ' ').trim()
  const lower = flat.toLowerCase()
  let at = -1
  for (const term of terms) {
    const i = lower.indexOf(term)
    if (i >= 0 && (at < 0 || i < at)) at = i
  }
  if (at < 0) return clip(flat, width)
  const start = Math.max(0, at - Math.floor(width / 3))
  const piece = flat.slice(start, start + width)
  return `${start > 0 ? '…' : ''}${piece}${start + width < flat.length ? '…' : ''}`
}

function countOf(haystack: string, needle: string): number {
  let n = 0
  let i = haystack.indexOf(needle)
  while (i >= 0 && n < 20) {
    n++
    i = haystack.indexOf(needle, i + needle.length)
  }
  return n
}

/** Ranks records by title (heaviest), tags, then body matches; the whole phrase scores extra. */
export function search(entries: readonly DecisionEntry[], query: string, limit = 10): SearchHit[] {
  const phrase = query.trim().toLowerCase()
  const terms = [...new Set(phrase.split(/[^\p{L}\p{N}_]+/u).filter(t => t.length > 0))]
  if (terms.length === 0) return []
  const hits: SearchHit[] = []
  for (const entry of entries) {
    const title = entry.title.toLowerCase()
    const tags = entry.tags.map(t => t.toLowerCase())
    const body = plainBody(entry).toLowerCase()
    let score = 0
    let matched = 0
    for (const term of terms) {
      const inTitle = countOf(title, term)
      const inTags = tags.filter(t => t === term).length * 2 + tags.filter(t => t.includes(term)).length
      const inBody = countOf(body, term)
      if (inTitle + inTags + inBody > 0) matched++
      score += inTitle * 6 + inTags * 4 + Math.min(inBody, 5)
    }
    if (matched === 0) continue
    score += matched === terms.length ? 5 : 0
    if (terms.length > 1 && (title.includes(phrase) || body.includes(phrase))) score += 8
    if (entry.status === 'superseded' || entry.status === 'rejected') score -= 1
    hits.push({ entry, score, snippet: snippetAround(plainBody(entry), terms) })
  }
  return hits.sort((a, b) => b.score - a.score || b.entry.id - a.entry.id).slice(0, limit)
}

export function formatSearch(hits: readonly SearchHit[], query: string): string {
  if (hits.length === 0) return `No decisions match "${query}".`
  return [
    `${hits.length} decision${hits.length === 1 ? '' : 's'} match "${query}", best first:`,
    ...hits.map(h => `${formatLine(h.entry)}\n    ${h.snippet}`),
  ].join('\n')
}

/** The full record for the model or a reader: the path, then the file as written. */
export function formatRecord(e: DecisionEntry): string {
  return `${e.path}\n\n${serializeDecision(e)}`
}

/** Markdown for the pane or the inline card: a meta line, then the body. */
export function recordMarkdown(e: DecisionEntry): string {
  const meta = [
    `**${e.status}**`,
    e.date,
    e.deciders.length > 0 ? `deciders: ${e.deciders.join(', ')}` : '',
    e.tags.length > 0 ? `tags: ${e.tags.join(', ')}` : '',
    e.supersedes.length > 0 ? `supersedes ${e.supersedes.map(n => `#${n}`).join(', ')}` : '',
    e.supersededBy.length > 0 ? `superseded by ${e.supersededBy.map(n => `#${n}`).join(', ')}` : '',
  ].filter(s => s !== '')
  const files = e.files.length > 0 ? `\n\nFiles: ${e.files.map(f => `\`${f}\``).join(', ')}` : ''
  const [heading, ...rest] = serializeBody(e).split('\n')
  return [heading, '', `${meta.join(' · ')}  \n\`${e.path}\`${files}`, ...rest].join('\n')
}

