// Parse

const SECTION_ALIASES: Record<string, 'context' | 'decision' | 'alternatives' | 'consequences'> = {
  context: 'context',
  'context and problem statement': 'context',
  'problem statement': 'context',
  problem: 'context',
  background: 'context',
  decision: 'decision',
  'decision outcome': 'decision',
  outcome: 'decision',
  'alternatives considered': 'alternatives',
  alternatives: 'alternatives',
  'considered options': 'alternatives',
  'options considered': 'alternatives',
  options: 'alternatives',
  consequences: 'consequences',
  implications: 'consequences',
}

/** Trims blank lines at both ends and trailing spaces on each line. */
function tidy(text: string): string {
  return text
    .split('\n')
    .map(l => l.replace(/[ \t]+$/, ''))
    .join('\n')
    .replace(/^\n+|\n+$/g, '')
}

/** A markdown list into items (continuation lines indented); a non-list text is one item. */
export function parseAlternatives(body: string): string[] {
  const text = tidy(body)
  if (text === '') return []
  const lines = text.split('\n')
  const items: string[] = []
  let isList = true
  for (const line of lines) {
    const bullet = /^\s{0,3}(?:[-*+]|\d+[.)])\s+(.*)$/.exec(line)
    if (bullet !== null) items.push(bullet[1] as string)
    else if (line.trim() === '') {
      if (items.length > 0) items[items.length - 1] += '\n'
    }
    else if (/^\s+/.test(line) && items.length > 0) items[items.length - 1] += `\n${line.replace(/^\s{1,4}/, '')}`
    else {
      isList = false
      break
    }
  }
  if (!isList) return [text]
  return items.map(tidy).filter(i => i !== '')
}

function emptyDecision(): Decision {
  return {
    id: 0,
    title: '',
    status: 'proposed',
    date: '',
    deciders: [],
    supersedes: [],
    supersededBy: [],
    tags: [],
    files: [],
    context: '',
    decision: '',
    alternatives: [],
    consequences: '',
    preamble: '',
    extraSections: [],
    extraMeta: [],
  }
}

/**
 * Parses a decision file, tolerating hand edits: CRLF, a BOM, no front matter, block or flow lists, quoted values,
 * MADR-style section names, missing sections. `fileName` gives the id and the title when the file lacks them.
 */
export function parseDecision(source: string, fileName?: string): Decision {
  const d = emptyDecision()
  const text = source.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n')
  let lines = text.split('\n')

  if ((lines[0] ?? '').trim() === '---') {
    const end = lines.findIndex((l, i) => i > 0 && (l.trim() === '---' || l.trim() === '...'))
    if (end > 0) {
      for (const meta of parseFrontMatter(lines.slice(1, end))) {
        const key = normKey(meta.key)
        switch (key) {
          case 'id': {
            const n = Number(/\d+/.exec(meta.scalar ?? '')?.[0])
            if (Number.isSafeInteger(n) && n > 0) d.id = n
            break
          }
          case 'title':
            d.title = oneLine(meta.scalar ?? listOf(meta).join(', '))
            break
          case 'status':
            d.status = normStatus(meta.scalar) ?? 'proposed'
            break
          case 'date':
            d.date = (meta.scalar ?? '').trim()
            break
          case 'deciders':
            d.deciders = listOf(meta)
            break
          case 'supersedes':
            d.supersedes = idsOf(meta)
            break
          case 'superseded-by':
            d.supersededBy = idsOf(meta)
            break
          case 'tags':
            d.tags = listOf(meta)
            break
          case 'files':
            d.files = listOf(meta)
            break
          default:
            d.extraMeta.push([meta.key, meta.raw])
        }
      }
      lines = lines.slice(end + 1)
    }
  }

  let current: { key: string; heading: string; lines: string[] } | undefined
  const preamble: string[] = []
  const sections: { key: string; heading: string; lines: string[] }[] = []
  let fence: string | undefined
  let sawTitle = false
  for (const line of lines) {
    const fenceMatch = /^\s{0,3}(`{3,}|~{3,})/.exec(line)
    if (fenceMatch !== null) {
      const marker = (fenceMatch[1] as string)[0] as string
      if (fence === undefined) fence = marker
      else if (fence === marker) fence = undefined
    }
    if (fence === undefined || fenceMatch !== null) {
      const h1 = fence === undefined ? /^#\s+(.+?)\s*#*\s*$/.exec(line) : null
      if (h1 !== null && !sawTitle && current === undefined && preamble.every(l => l.trim() === '')) {
        sawTitle = true
        const heading = (h1[1] as string).trim()
        const numbered = /^(?:ADR[-\s]?)?(\d+)\s*[.:)\-–—]\s*(.+)$/i.exec(heading)
        if (numbered !== null) {
          if (d.id === 0) d.id = Number(numbered[1])
          if (d.title === '') d.title = oneLine(numbered[2] as string)
        } else if (d.title === '') d.title = oneLine(heading)
        continue
      }
      const h2 = fence === undefined ? /^##\s+(.+?)\s*#*\s*$/.exec(line) : null
      if (h2 !== null) {
        const heading = (h2[1] as string).trim()
        const key = SECTION_ALIASES[heading.toLowerCase().replace(/[:.]+$/, '')] ?? `extra:${heading}`
        current = { key, heading, lines: [] }
        sections.push(current)
        continue
      }
    }
    if (current === undefined) preamble.push(line)
    else current.lines.push(line)
  }

  d.preamble = tidy(preamble.join('\n'))
  for (const section of sections) {
    const body = tidy(section.lines.join('\n'))
    const join = (a: string) => (a === '' ? body : body === '' ? a : `${a}\n\n${body}`)
    switch (section.key) {
      case 'context':
        d.context = join(d.context)
        break
      case 'decision':
        d.decision = join(d.decision)
        break
      case 'consequences':
        d.consequences = join(d.consequences)
        break
      case 'alternatives':
        d.alternatives = [...d.alternatives, ...parseAlternatives(body)]
        break
      default:
        d.extraSections.push({ heading: section.heading, body })
    }
  }

  if (d.id === 0 && fileName !== undefined) d.id = idFromFileName(fileName) ?? 0
  if (d.title === '' && fileName !== undefined) {
    d.title = oneLine(fileName.replace(/\.md$/i, '').replace(/^\d+[-_ ]*/, '').replace(/[-_]+/g, ' ')) || `Decision ${d.id}`
  }
  return d
}

// ---------------------------------------------------------------------------------------------------------------
// Serialize

const RESERVED = /^(true|false|yes|no|on|off|null|~|-?\d[\d_.,]*|0x[0-9a-f]+)$/i

function quote(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t')}"`
}

/** A scalar as plain YAML when that reads back the same, else double-quoted. */
export function yamlScalar(value: string): string {
  if (value === '') return '""'
  const isPlain = /^[A-Za-z0-9_./(@][^\n:#"'[\]{}]*$/.test(value) && !/\s$/.test(value) && !RESERVED.test(value) && !value.includes(': ')
  return isPlain ? value : quote(value)
}

function yamlItem(value: string): string {
  const isPlain = /^[A-Za-z0-9_./@+-][A-Za-z0-9_./@+ -]*$/.test(value) && !/\s$/.test(value) && !RESERVED.test(value) && !/^-\s/.test(value)
  return isPlain ? value : quote(value)
}

function yamlList(values: readonly (string | number)[]): string {
  return `[${values.map(v => (typeof v === 'number' ? String(v) : yamlItem(v))).join(', ')}]`
}

/** The markdown body (title heading and sections) without front matter: what a reader sees. */
export function serializeBody(d: Decision): string {
  const out: string[] = [`# ${d.id}. ${oneLine(d.title)}`, '']
  if (d.preamble !== '') out.push(d.preamble, '')
  const section = (heading: string, body: string) => {
    out.push(`## ${heading}`, '')
    if (body !== '') out.push(body, '')
  }
  section('Context', tidy(d.context))
  section('Decision', tidy(d.decision))
  section(
    'Alternatives considered',
    d.alternatives
      .map(tidy)
      .filter(a => a !== '')
      .map(a => `- ${a.split('\n').map(l => (l === '' ? '' : `  ${l}`)).join('\n').slice(2)}`)
      .join('\n'),
  )
  section('Consequences', tidy(d.consequences))
  for (const extra of d.extraSections) section(extra.heading, tidy(extra.body))
  while (out.length > 0 && out[out.length - 1] === '') out.pop()
  return `${out.join('\n')}\n`
}

/** Deterministic: fixed key order, flow lists, LF line endings, one trailing newline. */
export function serializeDecision(d: Decision): string {
  const meta = [
    '---',
    `id: ${d.id}`,
    `title: ${yamlScalar(oneLine(d.title))}`,
    `status: ${d.status}`,
    `date: ${yamlScalar(d.date)}`,
    `deciders: ${yamlList(d.deciders)}`,
    `supersedes: ${yamlList(d.supersedes)}`,
    `superseded-by: ${yamlList(d.supersededBy)}`,
    `tags: ${yamlList(d.tags)}`,
    `files: ${yamlList(d.files)}`,
    ...d.extraMeta.map(([k, raw]) => `${k}:${raw.startsWith('\n') || raw === '' ? '' : ' '}${raw}`),
    '---',
    '',
  ]
  return `${meta.join('\n')}${serializeBody(d)}`
}

