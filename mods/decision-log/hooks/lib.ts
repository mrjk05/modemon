// Pure helpers for decision-log: parsing, serializing, numbering, search and the text the tool returns.
import type { Decision, DecisionEntry, DecisionStatus } from '../types'

export const STATUSES: readonly DecisionStatus[] = ['proposed', 'accepted', 'superseded', 'rejected']
export const INDEX_FILE = 'README.md'
export const INDEX_MARKER = '<!-- generated by the decision-log plugin; edits here are overwritten -->'

// ---------------------------------------------------------------------------------------------------------------
// Small text helpers

export function pad4(id: number): string {
  return String(id).padStart(4, '0')
}

/** One line, collapsed whitespace, at most `max` characters. */
export function oneLine(text: string, max = 200): string {
  const flat = text.replace(/\s+/g, ' ').trim()
  return flat.length <= max ? flat : `${flat.slice(0, max - 1).trimEnd()}…`
}

export function clip(text: string, max: number): string {
  return text.length <= max ? text : `${text.slice(0, Math.max(max - 1, 1))}…`
}

/** Lowercase ASCII words joined by `-`, at most 60 characters, `decision` when nothing is left. */
export function slugify(title: string): string {
  const ascii = title.normalize('NFKD').replace(/[\u0300-\u036f]/g, '').toLowerCase()
  let slug = ascii.replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
  if (slug.length > 60) {
    const cut = slug.slice(0, 60)
    const lastDash = cut.lastIndexOf('-')
    slug = (lastDash >= 20 ? cut.slice(0, lastDash) : cut).replace(/-+$/g, '')
  }
  return slug === '' ? 'decision' : slug
}

export function fileName(id: number, title: string): string {
  return `${pad4(id)}-${slugify(title)}.md`
}

/** A file name inside the decisions folder that this plugin may read or write: no separators, no dot names. */
export function isSafeName(name: string): boolean {
  return name !== '' && name !== '.' && name !== '..' && !/[\\/\0]/.test(name) && !/^[A-Za-z]:/.test(name)
}

/** A decision file as named in a listing: `NNNN-anything.md`, the index excluded. */
export function isDecisionFile(name: string): boolean {
  return isSafeName(name) && /^\d+[-_ ].*\.md$/i.test(name) && name.toLowerCase() !== INDEX_FILE.toLowerCase()
}

export function idFromFileName(name: string): number | undefined {
  const match = /^(\d+)/.exec(name)
  if (match === null) return undefined
  const id = Number(match[1])
  return Number.isSafeInteger(id) && id > 0 ? id : undefined
}

export function isoDate(ms: number): string {
  return new Date(ms).toISOString().slice(0, 10)
}

/**
 * Validates the `dir` option: relative, `/`- or `\`-separated, no `.`/`..` segment. Answers the clean segments,
 * or an error.
 */
export function dirSegments(dir: string): { segments: string[] } | { error: string } {
  const trimmed = dir.trim()
  if (trimmed === '') return { error: 'the decisions folder option is empty' }
  if (/^([\\/]|[A-Za-z]:|~)/.test(trimmed)) return { error: `the decisions folder must be relative to the repository root, not "${trimmed}"` }
  const segments = trimmed.split(/[\\/]+/).filter(s => s !== '' && s !== '.')
  if (segments.length === 0) return { error: 'the decisions folder cannot be the repository root itself' }
  if (segments.some(s => s === '..' || /\0/.test(s))) return { error: `the decisions folder may not leave the repository ("${trimmed}")` }
  return { segments }
}

